def _clean(text):
    """把为可读性折行的字符串合成一行。"""
    return re.sub(r"\s+", " ", text).strip().replace("%%", "%")


def _title(direction, strategy, label):
    """按角度定制标题，避免统一套模板。"""
    if "评测" in label or "基准" in label:
        return "%s的统一评测与失败分析" % direction
    if "定义" in label:
        return "重新定义%s的问题边界" % direction
    if "机理" in label:
        return "%s的失效机理分析" % direction
    if "理论" in label:
        return "%s的理论解释与适用边界" % direction
    if "复现" in label:
        return "%s的大规模复现与偏差分析" % direction
    if strategy == "跨领域迁移":
        return "%s：借鉴%s" % (direction, label)
    return "%s的%s" % (direction, label)


def build(direction, mode="自动混合", limit=18, profile=None):
    """生成候选选题。每个候选带针对性理由、验证问题与最小实验。

    profile 可选：传入 profile_memory 的摘要（含 urgency/interest/mood/prefs）
    时，候选会按你的状态重新排序（只重排不删减），并附上排序理由。
    """
    direction = (direction or "").strip()
    if not direction:
        return []

    groups = []
    if mode in ("自动混合", "稳健邻接"):
        groups.append("稳健邻接")
    if mode in ("自动混合", "跨领域迁移"):
        groups.append("跨领域迁移")
    if mode in ("自动混合", "高风险高回报"):
        groups.append("高风险高回报")

    angles = []
    for g in groups:
        for item in ANGLES.get(g, []):
            angles.append((g,) + item)
    if not angles:
        for item in FALLBACK:
            angles.append(("稳健邻接",) + item)

    low = direction.lower()
    out = []
    seen = set()
    for i, (strategy, key, label, reason, question, min_exp, novelty, feas) in enumerate(angles):
        title = _title(direction, strategy, label)
        if title in seen:
            continue
        seen.add(title)

        relevance = 88 - min(20, i * 2)
        if key.lower() in low:
            relevance = min(95, relevance + 8)
        out.append({
            "title": title,
            "strategy": strategy,
            "angle": label,
            "angle_key": key,
            "reason": _clean(reason),
            # 只放这个角度自己的问题。原来这里还硬塞了两条通用检查
            # （「看不到预期差异怎么办」「和最近一篇工作差在哪」），结果 18 个
            # 候选 × 3 条 = 54 条里，有 36 条是这两句的重复，每个候选实际只
            # 有一条自己的信息量。通用检查移到 GENERIC_QUESTIONS，界面上作为
            # 整页的提醒显示一次。
            "questions": [_clean(question)],
            "min_experiment": _clean(min_exp),
            "relevance": int(relevance),
            "novelty": int(novelty),
            "feasibility": int(feas),
            "score": int(round(0.45 * relevance + 0.30 * novelty + 0.25 * feas)),
        })
        if len(out) >= limit:
            break
    if profile:
        apply_profile(out, profile)
    out.sort(key=lambda x: -x["score"])
    return out


# ---------------------------------------------------------------- 画像加权
# 设计原则（照搬数字生命的「注意力倾斜」）：
#   1. 只重排，不删除 —— 一条候选都不少，用户永远能看到全部 18 个；
#   2. 权重小 —— 最多 ±12 分，不能把本地客观分算出来的排序整个翻掉；
#   3. 必须交代 —— 每个被调整过的候选都带上人话理由，否则用户不知道
#      为什么这个排第一，会以为是随机。
# 分数是本地预估，不是结论；画像只改「先看哪个」。
TILT_CAP = 12.0

# 角度 → 偏好类别。疲了/要交差了推稳健，有精力/兴奋推新颖。
_STEADY = ("跨域泛化", "轻量化", "小样本", "评测", "复现", "工程", "部署")
_BOLD = ("定义", "机理", "理论", "新任务", "重构", "开放词汇", "可解释")


def _norm01(v, lo=0.0, hi=100.0):
    """把 0-100 的紧急度/兴趣压到 -1..1 附近再乘系数，避免单点极端。"""
    if hi <= lo:
        return 0.0
    x = (float(v) - lo) / (hi - lo)
    return max(-1.0, min(1.0, x * 2 - 1))


def apply_profile(cands, profile):
    """按画像给候选加 tilt，就地写入 cand["tilt"] / cand["tilt_reason"]。

    profile 结构（由 profile_memory.profile_brief() 提供，缺字段按默认值）：
        urgency  0-100  越接近截止越高
        interest 0-100  当前对这个方向的热度
        mood     焦虑/兴奋/平静/疲惫/困惑
        prefs    {"angle": {"轻量化": 3, ...}, "strategy": {...}}
    """
    try:
        urg = float(profile.get("urgency", 50) or 50)
        interest = float(profile.get("interest", 50) or 50)
        mood = (profile.get("mood") or "").strip()
        prefs = profile.get("prefs") or profile.get("preferences") or {}
    except Exception:
        urg, interest, mood, prefs = 50.0, 50.0, "", {}

    u = _norm01(urg)      # -1 时间充裕 … +1 火烧眉毛
    it = _norm01(interest)  # -1 没兴趣 … +1 很来劲
    tired = mood in ("疲惫", "焦虑", "困惑")

    angle_pref = (prefs.get("angle") or {}) if isinstance(prefs, dict) else {}
    strat_pref = (prefs.get("strategy") or {}) if isinstance(prefs, dict) else {}

    for c in cands:
        key = c.get("angle_key") or c.get("angle") or ""
        lab = c.get("angle") or ""
        strat = c.get("strategy") or ""
        parts = []   # [(分值, 理由)]，最后统一裁剪，保证理由与分数对得上

        # ① 紧急度：时间紧 → 稳健/可行性高的往前；时间松 → 新颖度往前
        feas = float(c.get("feasibility", 60))
        nov = float(c.get("novelty", 60))
        if u > 0.15:
            d1 = u * TILT_CAP * (feas - 70) / 30.0
            if abs(d1) >= 1.5:
                parts.append((d1, ("你时间紧，这条可行性 %.0f 分" % feas) if d1 > 0
                              else ("你时间紧，这条新颖度 %.0f 分但不好落" % nov)))
        elif u < -0.15:
            d1 = -u * TILT_CAP * (nov - 65) / 35.0
            if abs(d1) >= 1.5:
                parts.append((d1, ("你时间还宽裕，这条新颖度 %.0f 分" % nov) if d1 > 0
                              else ("你时间还宽裕，但这条可行性 %.0f 分偏低" % feas)))

        # ② 兴趣：来劲 → 偏高风险高回报；没兴趣 → 偏稳
        if it > 0.2 and (nov >= 75 or strat == "高风险高回报"):
            d2 = 3.0 * it
            if abs(d2) >= 1.5:
                parts.append((d2, "你把这个方向标得挺热"))
        elif it < -0.2 and feas >= 78:
            d2 = 2.5 * -it
            if abs(d2) >= 1.5:
                parts.append((d2, "这个方向你兴趣不高，先看容易出结果的"))

        # ③ 状态：疲惫/焦虑时别推高风险，容易半途而废
        if tired:
            if strat == "高风险高回报":
                parts.append((-5.0, "你状态不在峰值，高风险角度往后放"))
            if feas >= 80:
                parts.append((2.0, "你状态不在峰值，先给把握大的"))

        # ④ 历史偏好：存过/挑过角度加权（至少 3 次才起作用）
        for name in (key, lab):
            n = angle_pref.get(name) or 0
            if isinstance(n, (int, float)) and n >= 3:
                parts.append((min(4.0, 0.6 * n), "你以前多次挑这类角度"))
                break
        ns = strat_pref.get(strat) or 0
        if isinstance(ns, (int, float)) and ns >= 3:
            parts.append((min(3.0, 0.5 * ns), "你常在这类策略里选题"))

        tilt = sum(p[0] for p in parts)
        tilt = max(-TILT_CAP, min(TILT_CAP, tilt))
        # 只有真的被挪动过才写理由；分值为正的写「+7 可行性 85 分」
        why = [p[1] for p in parts if abs(p[0]) >= 1.5]
        c["tilt"] = round(tilt, 1)
        # 分数挪了 ≥1.5 就必须有理由，否则用户看到「明明分数低却排前面」会迷惑
        c["tilt_reason"] = "；".join(why) if abs(tilt) >= 1.5 else ""
        c["base_score"] = c.get("score", 0)
        c["score"] = int(round(c.get("score", 0) + tilt))
    return cands
def main():
    # 领域清单必须用引擎自己的加载函数：它会合并
    # directions_library.json 与 research_taxonomy_comprehensive.json，
    # 直接读文件只能拿到主库的 64 个领域，会误判大量有效领域「不存在」。
    import kb_widget as kb
    lib = kb.load_direction_library()      # {大类: {subs:[...]}}，合并后 387 个领域
    valid = set()
    for cat, entry in lib.items():
        for sub in entry.get("subs", []):
            valid.add((cat, sub.get("name")))
    print("可用领域:", len(valid))

    aliases_doc = json.loads((HERE / "direction_aliases.json").read_text(encoding="utf-8"))
    aliases = aliases_doc["aliases"] if isinstance(aliases_doc, dict) else aliases_doc
    by_field = {}
    for e in aliases:
        by_field.setdefault((e.get("category"), e.get("field")), []).append(e)

    added, skipped = 0, []
    for terms, cat, field in EXTRA:
        if (cat, field) not in valid:
            skipped.append("%s / %s（方向库中不存在该领域）" % (cat, field))
            continue
        e = by_field.get((cat, field))
        if e:
            entry = e[0]
        else:
            entry = {"category": cat, "field": field, "terms": [field]}
            aliases.append(entry)
            by_field[(cat, field)] = [entry]
        existing = set(t.lower() for t in entry["terms"])
        for t in terms:
            if t.lower() not in existing:
                entry["terms"].append(t)
                existing.add(t.lower())
                added += 1

    # 写回时保持原文件结构 {"aliases": [...]}
    if isinstance(aliases_doc, dict):
        aliases_doc["aliases"] = aliases
        out = aliases_doc
    else:
        out = aliases
    (HERE / "direction_aliases.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")

    print("别名组:", len(aliases), " 新增口语说法:", added)
    for s in skipped:
        print("  跳过:", s)


if __name__ == "__main__":
    main()
def neighbors(field):
    """返回该领域的近邻方向（不含自身）。"""
    if not field:
        return []
    return [x for x in NEIGHBORS.get(field, []) if x]


def expand(field, limit=4):
    """返回 [自身] + 近邻，用于检索时放宽范围。"""
    out = [field] if field else []
    for n in neighbors(field):
        if n not in out:
            out.append(n)
        if len(out) >= limit + 1:
            break
    return out